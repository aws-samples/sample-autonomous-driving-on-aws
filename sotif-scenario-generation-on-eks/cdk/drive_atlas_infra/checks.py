"""Security rule exceptions (cdk-nag AwsSolutions, checkov), each with the reason it is not fixed in this sample.

cdk-nag runs on every synth (app.py). checkov reads the same reasons from the template Metadata, so ASH scans of
cdk.out report them as suppressed rather than open.
"""

from typing import Optional, Sequence

import jsii
from aws_cdk import CfnResource, IAspect
from cdk_nag import NagPackSuppression, NagSuppressions, RegexAppliesTo
from constructs import IConstruct


def nag(scope: IConstruct, rule: str, reason: str, applies_to: Optional[Sequence[str]] = None) -> None:
    """Acknowledge an AwsSolutions rule on scope and its children; applies_to holds regexes for the finding ids."""
    regexes = [RegexAppliesTo(regex=f"/{pattern}/") for pattern in applies_to] if applies_to else None
    NagSuppressions.add_resource_suppressions(scope, [NagPackSuppression(id=rule, reason=reason, applies_to=regexes)], apply_to_children=True)


def checkov(resource: IConstruct, check: str, reason: str) -> None:
    cfn = resource if isinstance(resource, CfnResource) else resource.node.default_child
    meta = cfn.get_metadata("checkov") or {"skip": []}
    meta["skip"].append({"id": check, "comment": reason})
    cfn.add_metadata("checkov", meta)


@jsii.implements(IAspect)
class LambdaHandlers:
    """CDK custom resource handlers (CloudFormation invokes them) and the roles that CDK's CustomResourceProvider
    creates for them."""

    FUNCTION_REASON = ("CDK custom resource handler: invoked synchronously by CloudFormation, so a DLQ and reserved "
                       "concurrency do not apply; no secrets in environment variables")
    PROVIDER_ROLE_REASON = "Role generated by aws-cdk-lib's CustomResourceProvider for its own handler; not configurable from this app."

    def visit(self, node: IConstruct) -> None:
        if not isinstance(node, CfnResource):
            return
        if node.cfn_resource_type == "AWS::Lambda::Function":
            for check in ("CKV_AWS_115", "CKV_AWS_116", "CKV_AWS_117", "CKV_AWS_173"):
                checkov(node, check, self.FUNCTION_REASON)
        elif node.cfn_resource_type == "AWS::IAM::Role" and "CustomResourceProvider" in node.node.path:
            for check in ("CKV_AWS_107", "CKV_AWS_108", "CKV_AWS_109", "CKV_AWS_110", "CKV_AWS_111"):
                checkov(node, check, self.PROVIDER_ROLE_REASON)
