#!/usr/bin/env node
import * as cdk from 'aws-cdk-lib';
import { AwsSolutionsChecks, NagSuppressions } from 'cdk-nag';
import { CoreStack } from '../lib/core-stack';
import { EksStack } from '../lib/eks-stack';
import { OpenSearchStack } from '../lib/opensearch-stack';

const app = new cdk.App();

// Environment - use CLI config or specify explicitly
const env = {
  account: process.env.CDK_DEFAULT_ACCOUNT,
  region: process.env.CDK_DEFAULT_REGION || 'ap-northeast-2',
};

// Context values (can be set via cdk.json or -c flag)
const vpcId = app.node.tryGetContext('vpcId'); // Optional: use existing VPC

// 1. Core infrastructure
const coreStack = new CoreStack(app, 'CosmosCurateCore', {
  env,
  vpcId,
  description: 'Core infrastructure: VPC, S3, ECR',
});

// 2. EKS cluster
const eksStack = new EksStack(app, 'CosmosCurateEks', {
  env,
  vpc: coreStack.vpc,
  bucket: coreStack.bucket,
  description: 'EKS cluster, CPU node groups, Pod Identity for Cosmos Curator',
});
eksStack.addStackDependency(coreStack);

// 3. OpenSearch Serverless for embeddings
const openSearchStack = new OpenSearchStack(app, 'CosmosCurateOpenSearch', {
  env,
  principalArns: [
    eksStack.cluster.role.roleArn,      // EKS cluster role
    eksStack.curatorRole.roleArn,        // Curator Pod role
    // Add more ARNs as needed (e.g., your user role for testing)
  ],
  description: 'OpenSearch Serverless collection for video embeddings',
});
openSearchStack.addStackDependency(eksStack);

// Tags for all stacks
cdk.Tags.of(app).add('Project', 'cosmos-curate-eks');
cdk.Tags.of(app).add('ManagedBy', 'CDK');

// cdk-nag: every finding is either fixed or suppressed below with the reason
cdk.Aspects.of(app).add(new AwsSolutionsChecks({ verbose: true }));

NagSuppressions.addResourceSuppressions(coreStack.bucket, [
  { id: 'AwsSolutions-S1', reason: 'Sample: no server access logging to keep cost down. Enable it for production data.' },
]);
if (!vpcId) {
  NagSuppressions.addResourceSuppressionsByPath(coreStack, '/CosmosCurateCore/CosmosCurateVpc/Resource', [
    { id: 'AwsSolutions-VPC7', reason: 'Sample: no VPC flow logs to keep cost down. Enable them for production.' },
  ]);
}

NagSuppressions.addResourceSuppressionsByPath(eksStack, '/CosmosCurateEks/CosmosCurateCluster/Resource/Resource/Default', [
  { id: 'AwsSolutions-EKS1', reason: 'kubectl runs from the build host. Restrict with -c publicAccessCidrs=<cidr,...> (see README Security).' },
  { id: 'AwsSolutions-EKS2', reason: 'Sample: control plane logging is off to keep cost down. Enable it for production.' },
]);
NagSuppressions.addStackSuppressions(eksStack, [
  {
    id: 'AwsSolutions-IAM4',
    reason: 'AWS managed policies required by EKS (cluster, node group, CNI, ECR read) and by the CDK-generated EKS/kubectl provider Lambdas.',
  },
]);
for (const provider of ['@aws-cdk--aws-eks.ClusterResourceProvider', '@aws-cdk--aws-eks.KubectlProvider']) {
  NagSuppressions.addResourceSuppressionsByPath(eksStack, `/CosmosCurateEks/${provider}`, [
    { id: 'AwsSolutions-IAM4', reason: 'Lambda basic execution role generated by aws-cdk-lib aws-eks.' },
    { id: 'AwsSolutions-IAM5', reason: 'Generated by aws-cdk-lib aws-eks; not configurable.' },
    { id: 'AwsSolutions-L1', reason: 'Runtime chosen by aws-cdk-lib aws-eks; not configurable.' },
    { id: 'AwsSolutions-SF1', reason: 'Waiter state machine generated by aws-cdk-lib aws-eks; not configurable.' },
    { id: 'AwsSolutions-SF2', reason: 'Waiter state machine generated by aws-cdk-lib aws-eks; not configurable.' },
  ], true);
}
NagSuppressions.addResourceSuppressionsByPath(eksStack, '/CosmosCurateEks/CosmosCurateCluster/Resource/CreationRole/DefaultPolicy/Resource', [
  { id: 'AwsSolutions-IAM5', reason: 'Cluster creation role generated by aws-cdk-lib aws-eks.' },
]);
NagSuppressions.addResourceSuppressions(eksStack.curatorRole, [
  {
    id: 'AwsSolutions-IAM5',
    reason: 'S3 object wildcards are scoped to this sample bucket (CDK grantReadWrite). Bedrock: one model; the global inference profile routes it to any region. AOSS: collections in this account and region.',
  },
], true);


app.synth();
